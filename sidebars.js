/**
 * Learning and practice are intentionally separate navigation modes.
 * Topic metadata is shared with the homepage, navbar, footer, and callouts;
 * add new topics to src/data/topics.js and provide matching docs folders.
 *
 * @type {import('@docusaurus/plugin-content-docs').SidebarsConfig}
 */
import {topics} from './src/data/topics.js';

const sidebars = {
  learnSidebar: topics.map((topic) => ({
    type: 'category',
    label: topic.title,
    collapsed: true,
    collapsible: true,
    link: {
      type: 'generated-index',
      slug: `/category/${topic.slug}`,
      description: topic.description,
    },
    items: [{type: 'autogenerated', dirName: topic.slug}],
  })),
  questionBankSidebar: [
    {
      type: 'doc',
      id: 'question-bank/index',
      label: 'Question Bank Overview',
      className: 'sidebar-practice-overview',
    },
    ...topics.map((topic) => ({
      type: 'doc',
      id: `question-bank/${topic.slug}`,
      label: `${topic.title} · ${topic.questionCount}`,
    })),
  ],
};

export default sidebars;
